-- =====================================================================
-- Centralized Procurement Management System - PostgreSQL schema
-- Matches the ER diagram: 14 tables (E1 workflow, E2 vendor, E3 integrity, E4 stock)
--
-- Run:  createdb procureflow
--       psql -d procureflow -f procureflow_schema.sql
-- Note: USER is a reserved word in PostgreSQL, so that table is named app_user.
-- =====================================================================

-- ---------- Master data ----------
CREATE TABLE vendor (
    vendor_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL UNIQUE
);

CREATE TABLE product (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL UNIQUE
);

-- ---------- E1: users and roles ----------
CREATE TABLE app_user (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL,
    email         TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role          TEXT NOT NULL
                  CHECK (role IN ('Customer','Shopkeeper','Vendor','Warehouse','Finance')),
    vendor_id     BIGINT REFERENCES vendor(vendor_id),
    -- only Vendor users may be linked to a vendor
    CHECK (vendor_id IS NULL OR role = 'Vendor')
);

-- ---------- E4: vendor stock (never below 0; version for concurrency) ----------
CREATE TABLE vendor_stock (
    vendor_id  BIGINT NOT NULL REFERENCES vendor(vendor_id),
    product_id BIGINT NOT NULL REFERENCES product(product_id),
    stock_qty  INTEGER NOT NULL CHECK (stock_qty >= 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price > 0),
    version    INTEGER NOT NULL DEFAULT 1,
    PRIMARY KEY (vendor_id, product_id)
);

-- ---------- E1: purchase request and status flow ----------
CREATE TABLE purchase_request (
    request_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT NOT NULL REFERENCES app_user(user_id),
    product_id   BIGINT NOT NULL REFERENCES product(product_id),
    quantity     INTEGER NOT NULL CHECK (quantity > 0),
    status       TEXT NOT NULL DEFAULT 'Pending'
                 CHECK (status IN ('Pending','Approved','Rejected','Vendor Selected',
                                   'Ordered','Received','Completed')),
    approved_by  BIGINT REFERENCES app_user(user_id),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE request_status_history (
    history_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  BIGINT NOT NULL REFERENCES purchase_request(request_id),
    from_status TEXT,
    to_status   TEXT NOT NULL,
    changed_by  BIGINT NOT NULL REFERENCES app_user(user_id),
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- E2: vendor enquiries ----------
CREATE TABLE enquiry (
    enquiry_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id    BIGINT NOT NULL REFERENCES purchase_request(request_id),
    vendor_id     BIGINT NOT NULL REFERENCES vendor(vendor_id),
    status        TEXT NOT NULL DEFAULT 'Sent'
                  CHECK (status IN ('Sent','Confirmed','Rejected','No response')),
    available_qty INTEGER CHECK (available_qty >= 0),
    sent_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    responded_at  TIMESTAMPTZ,
    UNIQUE (request_id, vendor_id)
);

-- ---------- E3: order, receipt, invoice, reconciliation, payment ----------
CREATE TABLE purchase_order (
    order_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL UNIQUE REFERENCES purchase_request(request_id), -- one order per request
    vendor_id  BIGINT NOT NULL REFERENCES vendor(vendor_id),                   -- one vendor only
    quantity   INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price > 0),
    status     TEXT NOT NULL DEFAULT 'Ordered'
               CHECK (status IN ('Ordered','Received','Completed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE goods_receipt (
    receipt_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT NOT NULL UNIQUE REFERENCES purchase_order(order_id),
    received_qty INTEGER NOT NULL CHECK (received_qty >= 0),
    received_by  BIGINT NOT NULL REFERENCES app_user(user_id),
    received_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE invoice (
    invoice_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no  TEXT NOT NULL UNIQUE,                                  -- duplicate numbers rejected
    order_id    BIGINT NOT NULL UNIQUE REFERENCES purchase_order(order_id),
    invoice_qty INTEGER NOT NULL CHECK (invoice_qty > 0),
    amount      NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE reconciliation (
    recon_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT NOT NULL UNIQUE REFERENCES purchase_order(order_id),
    receipt_id      BIGINT NOT NULL REFERENCES goods_receipt(receipt_id),
    invoice_id      BIGINT NOT NULL REFERENCES invoice(invoice_id),
    result          TEXT NOT NULL CHECK (result IN ('Match','Mismatch')),
    mismatch_reason TEXT,
    checked_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE payment (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL UNIQUE REFERENCES invoice(invoice_id),  -- an invoice is paid once
    amount     NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    paid_by    BIGINT NOT NULL REFERENCES app_user(user_id),
    paid_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- E1: notifications ----------
CREATE TABLE notification (
    notif_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES app_user(user_id),
    request_id BIGINT REFERENCES purchase_request(request_id),
    event      TEXT NOT NULL,
    status     TEXT NOT NULL DEFAULT 'Pending'
               CHECK (status IN ('Pending','Delivered','Failed')),
    retries    INTEGER NOT NULL DEFAULT 0 CHECK (retries >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- E3: audit log ----------
CREATE TABLE audit_log (
    log_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT NOT NULL REFERENCES app_user(user_id),
    action    TEXT NOT NULL,
    entity    TEXT NOT NULL,
    entity_id BIGINT,
    details   TEXT,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- Indexes (fast vendor search, status queries, lookups)
-- =====================================================================
CREATE INDEX idx_stock_product   ON vendor_stock(product_id, stock_qty);
CREATE INDEX idx_request_status  ON purchase_request(status, created_at);
CREATE INDEX idx_request_user    ON purchase_request(requester_id);
CREATE INDEX idx_history_request ON request_status_history(request_id, changed_at);
CREATE INDEX idx_enquiry_request ON enquiry(request_id);
CREATE INDEX idx_notif_user      ON notification(user_id, status);
CREATE INDEX idx_audit_entity    ON audit_log(entity, entity_id);

-- =====================================================================
-- Rules enforced by the database itself
-- =====================================================================

-- E1: only valid status steps are allowed (no skipping, no going back)
CREATE OR REPLACE FUNCTION check_status_flow() RETURNS trigger AS $$
BEGIN
    IF NEW.status = OLD.status THEN
        RETURN NEW;
    END IF;
    IF NOT (
        (OLD.status = 'Pending'         AND NEW.status IN ('Approved','Rejected')) OR
        (OLD.status = 'Approved'        AND NEW.status = 'Vendor Selected') OR
        (OLD.status = 'Vendor Selected' AND NEW.status = 'Ordered') OR
        (OLD.status = 'Ordered'         AND NEW.status = 'Received') OR
        (OLD.status = 'Received'        AND NEW.status = 'Completed')
    ) THEN
        RAISE EXCEPTION 'Invalid status change: % -> %', OLD.status, NEW.status;
    END IF;
    NEW.updated_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_status_flow
    BEFORE UPDATE OF status ON purchase_request
    FOR EACH ROW EXECUTE FUNCTION check_status_flow();

-- E3: payment is allowed only after the 3-way match passed
CREATE OR REPLACE FUNCTION check_payment_allowed() RETURNS trigger AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM reconciliation
        WHERE invoice_id = NEW.invoice_id AND result = 'Match'
    ) THEN
        RAISE EXCEPTION 'Payment refused: order, receipt and invoice do not match';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_payment_needs_match
    BEFORE INSERT ON payment
    FOR EACH ROW EXECUTE FUNCTION check_payment_allowed();

-- E3: audit records can never be edited or deleted
CREATE OR REPLACE FUNCTION audit_immutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit records are immutable';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_immutable
    BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION audit_immutable();

